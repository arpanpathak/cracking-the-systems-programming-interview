// ch19/free_list_allocator.rs: a first-fit allocator with splitting and coalescing.
use std::alloc::{self, Layout};
use std::ptr;

const ALIGNMENT: usize = 16;
const ARENA_BYTES: usize = 1024;
const HEADER_BYTES: usize = size_of::<BlockHeader>();
const MINIMUM_SPLIT_BYTES: usize = HEADER_BYTES + ALIGNMENT;

/// Stored immediately before every payload. The list links blocks in address order.
#[repr(C, align(16))]
struct BlockHeader {
    payload_bytes: usize,
    is_free: bool,
    next: *mut BlockHeader,
}

/// Rounds `value` up to the next multiple of ALIGNMENT.
fn align_up(value: usize) -> usize {
    (value + ALIGNMENT - 1) & !(ALIGNMENT - 1)
}

struct FreeListAllocator {
    arena: *mut u8,
    layout: Layout,
    first: *mut BlockHeader,
}

impl FreeListAllocator {
    /// Obtains the arena and makes it one free block.
    /// Returns None if no memory is available.
    fn new() -> Option<Self> {
        let layout = Layout::from_size_align(ARENA_BYTES, ALIGNMENT).ok()?;

        // SAFETY: `Layout::from_size_align` verified `ARENA_BYTES > 0` and `ALIGNMENT == 16`
        // is a valid power of two. The global allocator returns a pointer aligned to 16 bytes.
        let arena = unsafe { alloc::alloc(layout) };
        if arena.is_null() {
            return None;
        }

        let first = arena.cast::<BlockHeader>();
        let whole_arena = BlockHeader {
            payload_bytes: ARENA_BYTES - HEADER_BYTES,
            is_free: true,
            next: ptr::null_mut(),
        };

        // SAFETY: `first` is non-null, aligned to 16 bytes by `alloc::alloc`, and points to
        // uninitialized memory of size `ARENA_BYTES >= HEADER_BYTES`. Writing the root header
        // establishes the base invariant for the intrusive free-list.
        unsafe { first.write(whole_arena) };

        Some(FreeListAllocator { arena, layout, first })
    }

    /// Returns a payload of at least `requested_bytes`, or None when no block fits.
    fn allocate(&mut self, requested_bytes: usize) -> Option<*mut u8> {
        // A larger request can never fit, and rounding it up could overflow.
        if requested_bytes > ARENA_BYTES {
            return None;
        }

        let payload_bytes = align_up(requested_bytes);
        let block = self.find_first_fit(payload_bytes)?;

        // SAFETY:
        // 1. `block` is guaranteed by `find_first_fit` to be a valid, aligned `BlockHeader`
        //    with `payload_bytes <= block.payload_bytes`.
        // 2. `split_if_large` preserves the 16-byte alignment of any newly created tail block.
        // 3. Adding `HEADER_BYTES` yields the start of the usable user payload, which is
        //    strictly aligned to 16 bytes because `sizeof(BlockHeader) == 24` padded to 32 bytes (or multiple of 16).
        unsafe {
            Self::split_if_large(block, payload_bytes);
            (*block).is_free = false;

            Some(block.cast::<u8>().add(HEADER_BYTES))
        }
    }

    /// Marks the block free and merges it with free neighbors.
    ///
    /// # Safety
    /// `payload` must be a pointer that `allocate` returned on this allocator, and
    /// it must not have been released since.
    unsafe fn release(&mut self, payload: *mut u8) {
        // SAFETY: Invariant Contract:
        // Because `payload` was generated by `allocate()`, the user payload is located
        // exactly `HEADER_BYTES` past its controlling `BlockHeader`. Subtracting `HEADER_BYTES`
        // reconstructs the original header address. Setting `is_free = true` re-enters this
        // block into the pool of recyclable memory.
        unsafe {
            let block = payload.sub(HEADER_BYTES).cast::<BlockHeader>();
            (*block).is_free = true;
        }

        self.coalesce();
    }

    fn find_first_fit(&self, payload_bytes: usize) -> Option<*mut BlockHeader> {
        let mut block = self.first;

        while !block.is_null() {
            // SAFETY: Invariant Induction:
            // Every non-null pointer in the intrusive list originated from the initial root header
            // or a validated split/coalesce operation within the arena bounds.
            let header = unsafe { &*block };

            if header.is_free && header.payload_bytes >= payload_bytes {
                return Some(block);
            }

            block = header.next;
        }

        None
    }

    /// Merges every pair of free blocks that are next to each other.
    fn coalesce(&mut self) {
        let mut block = self.first;

        // SAFETY: Invariant Proof:
        // `block` and `following` are live, initialized headers. Adjacency is verified by
        // address ordering: because the list is sorted by physical address, two free blocks
        // are physically contiguous if `block + HEADER_BYTES + payload_bytes == following`.
        // Merging absorbs `following` into `block` by adding `HEADER_BYTES + following.payload_bytes`,
        // perfectly conserving arena capacity without memory leaks.
        unsafe {
            while !(*block).next.is_null() {
                let following = (*block).next;

                if (*block).is_free && (*following).is_free {
                    (*block).payload_bytes += HEADER_BYTES + (*following).payload_bytes;
                    (*block).next = (*following).next;
                    continue;
                }

                block = following;
            }
        }
    }

    fn print_blocks(&self, title: &str) {
        println!("{title}");

        let mut block = self.first;

        while !block.is_null() {
            // SAFETY: Read-only traversal across non-null intrusive block pointers within the arena.
            let header = unsafe { &*block };

            let offset = block as usize - self.arena as usize;
            let state = if header.is_free { "free" } else { "used" };

            println!("  offset {offset:4}  payload {:4}  {state}", header.payload_bytes);

            block = header.next;
        }
    }

    /// Cuts the unused tail of `block` into a new free block, if the tail is large enough.
    ///
    /// # Safety
    /// `block` must be a live header whose payload holds at least `payload_bytes`.
    unsafe fn split_if_large(block: *mut BlockHeader, payload_bytes: usize) {
        // SAFETY: Splitting Invariant Proof:
        // `spare_bytes >= MINIMUM_SPLIT_BYTES` guarantees the remainder can house a full
        // `BlockHeader` plus at least 16 bytes of aligned payload. The address
        // `tail = block + HEADER_BYTES + payload_bytes` is a multiple of 16, ensuring proper
        // alignment for the new header and preventing degenerate runt blocks.
        unsafe {
            let spare_bytes = (*block).payload_bytes - payload_bytes;
            if spare_bytes < MINIMUM_SPLIT_BYTES {
                return;
            }

            let tail = block
                .cast::<u8>()
                .add(HEADER_BYTES + payload_bytes)
                .cast::<BlockHeader>();

            tail.write(BlockHeader {
                payload_bytes: spare_bytes - HEADER_BYTES,
                is_free: true,
                next: (*block).next,
            });

            (*block).payload_bytes = payload_bytes;
            (*block).next = tail;
        }
    }
}

impl Drop for FreeListAllocator {
    fn drop(&mut self) {
        // SAFETY: Releases the backing heap buffer to the global allocator using the exact base
        // pointer and layout descriptor supplied during `alloc::alloc`.
        unsafe { alloc::dealloc(self.arena, self.layout) };
    }
}

fn main() {
    let Some(mut heap) = FreeListAllocator::new() else {
        eprintln!("the arena could not be allocated");
        return;
    };

    println!("arena {ARENA_BYTES} bytes, header {HEADER_BYTES} bytes\n");

    let requests = (heap.allocate(100), heap.allocate(200), heap.allocate(300));
    let (Some(first), Some(second), Some(third)) = requests else {
        eprintln!("the arena is too small for the three requests");
        return;
    };

    heap.print_blocks("after allocate(100), allocate(200), allocate(300):");

    // SAFETY: Invariant Contract:
    // `second` is an active allocation pointer returned by `allocate(200)` and has not
    // been previously released, ensuring no double-free corruption of intrusive headers.
    unsafe { heap.release(second) };
    heap.print_blocks("\nafter release(second):");

    let Some(fourth) = heap.allocate(150) else {
        eprintln!("no block fits 150 bytes");
        return;
    };

    heap.print_blocks("\nafter allocate(150):");

    let reused = if fourth == second { "yes" } else { "no" };
    println!("fourth reuses the block of second: {reused}");

    // SAFETY: Lifetime & Ownership Proof:
    // Pointers `first`, `fourth`, and `third` are active allocations each released exactly once.
    // Notice that `second` is not released here: its physical block was split and reallocated
    // under exclusive ownership to `fourth`. Releasing `fourth` recycles that memory correctly.
    unsafe {
        heap.release(first);
        heap.release(fourth);
        heap.release(third);
    }

    heap.print_blocks("\nafter releasing everything:");
}
